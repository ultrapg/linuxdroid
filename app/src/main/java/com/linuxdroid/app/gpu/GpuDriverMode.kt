package com.linuxdroid.app.gpu

enum class GpuDriverMode(val id: String, val title: String, val subtitle: String) {
    AUTO(
        "auto",
        "Automatic (Recommended)",
        "Uses native Turnip Vulkan + Zink OpenGL on Snapdragon Adreno, and Venus Vulkan + VirGL on MediaTek, Exynos, and Tensor."
    ),
    UNIFIED(
        "unified",
        "Unified Vulkan + VirGL (All Chipsets)",
        "Runs Vulkan and OpenGL over Android's native GPU driver across Snapdragon, MediaTek, Exynos, and Tensor."
    ),
    TURNIP(
        "turnip",
        "Adreno Turnip + Zink (Snapdragon)",
        "Direct /dev/kgsl-3d0 Mesa Turnip Vulkan 1.3 and Zink OpenGL 4.6 for Qualcomm Adreno GPUs."
    ),
    SOFTWARE(
        "software",
        "Software Rendering (Safe Mode)",
        "CPU-rendered OpenGL and Vulkan (LLVMpipe + Lavapipe) for maximum compatibility."
    );

    companion object {
        fun fromId(id: String?): GpuDriverMode =
            entries.firstOrNull { it.id.equals(id, ignoreCase = true) } ?: AUTO
    }
}

data class ResolvedGpuConfig(
    val requestedMode: GpuDriverMode,
    val activeBackend: String, // "turnip", "unified", or "software"
    val summary: String,
    val requiresVirglServer: Boolean,
    val enableVenus: Boolean,
    val envVars: Map<String, String>,
) {
    fun toEnvFileContent(): String = buildString {
        append("# Auto-generated by LinuxDroid GPU Driver Manager\n")
        for ((k, v) in envVars) {
            val escaped = v.replace("\\", "\\\\").replace("\"", "\\\"")
            append(k).append("=\"").append(escaped).append("\"\n")
        }
    }
}

object GpuConfigGenerator {
    private const val ICD_DIR = "/usr/share/vulkan/icd.d"
    private const val FREEDRENO_ICD = "$ICD_DIR/freedreno_icd.aarch64.json"
    private const val VIRTIO_ICD = "$ICD_DIR/virtio_icd.aarch64.json"
    private const val PANFROST_ICD = "$ICD_DIR/panfrost_icd.aarch64.json"
    private const val LVP_ICD = "$ICD_DIR/lvp_icd.aarch64.json"

    fun resolve(
        requested: GpuDriverMode,
        gpu: GpuInfo,
        virglSocketGuestPath: String,
    ): ResolvedGpuConfig {
        val backend = when (requested) {
            GpuDriverMode.AUTO -> when {
                gpu.supportsTurnipKgsl -> "turnip"
                gpu.hasVulkan || gpu.hasMaliNode || gpu.family != GpuFamily.OTHER -> "unified"
                else -> "software"
            }
            GpuDriverMode.TURNIP -> if (gpu.hasKgslNode) "turnip" else "unified"
            GpuDriverMode.UNIFIED -> "unified"
            GpuDriverMode.SOFTWARE -> "software"
        }

        val env = LinkedHashMap<String, String>()
        env["LINUXDROID_GPU_MODE"] = requested.id
        env["LINUXDROID_GPU_ACTIVE"] = backend
        env["LINUXDROID_GPU_FAMILY"] = gpu.family.name.lowercase()
        env["MESA_DISK_CACHE_DATABASE"] = "1"
        env["MESA_SHADER_CACHE_MAX_SIZE"] = "512M"

        return when (backend) {
            "turnip" -> {
                val summary = "Turnip Vulkan 1.3 + Zink OpenGL 4.6 (${gpu.deviceName})"
                env["LINUXDROID_GPU_SUMMARY"] = summary
                env["VK_DRIVER_FILES"] = FREEDRENO_ICD
                env["VK_ICD_FILENAMES"] = FREEDRENO_ICD
                env["TU_DEBUG"] = "noconform"
                env["MESA_VK_WSI_DEBUG"] = "sw"
                env["MESA_VK_WSI_PRESENT_MODE"] = "mailbox"
                env["MESA_LOADER_DRIVER_OVERRIDE"] = "zink"
                env["GALLIUM_DRIVER"] = "zink"
                env["ZINK_DESCRIPTORS"] = "lazy"
                env["LIBGL_KOPPER_DRI2"] = "true"
                env["QT_WAYLAND_FORCE_NONBLOCKING_SWAP_SUPPORT"] = "1"
                ResolvedGpuConfig(
                    requestedMode = requested,
                    activeBackend = "turnip",
                    summary = summary,
                    requiresVirglServer = false,
                    enableVenus = false,
                    envVars = env,
                )
            }
            "unified" -> {
                val enableVenus = gpu.supportsUnifiedVenus
                val vkIcds = buildList {
                    if (gpu.hasDriRenderNode && (gpu.family == GpuFamily.MALI || gpu.family == GpuFamily.IMMORTALIS)) {
                        add(PANFROST_ICD)
                    }
                    if (enableVenus) add(VIRTIO_ICD)
                    if (isEmpty()) add(LVP_ICD)
                }.joinToString(":")

                val summary = if (enableVenus) {
                    "Venus Vulkan + VirGL/Zink OpenGL (${gpu.deviceName})"
                } else {
                    "VirGL OpenGL + Lavapipe Vulkan (${gpu.deviceName})"
                }
                env["LINUXDROID_GPU_SUMMARY"] = summary
                env["VTEST_SOCKET_NAME"] = virglSocketGuestPath
                env["VK_DRIVER_FILES"] = vkIcds
                env["VK_ICD_FILENAMES"] = vkIcds
                if (enableVenus) {
                    env["VN_DEBUG"] = "vtest"
                }
                if (gpu.hasDriRenderNode || gpu.hasMaliNode) {
                    env["LIBGL_ALWAYS_SOFTWARE"] = "1"
                    env["GALLIUM_DRIVER"] = "virpipe"
                    env["MESA_GL_VERSION_OVERRIDE"] = "4.3COMPAT"
                    env["MESA_GLSL_VERSION_OVERRIDE"] = "430"
                    if (gpu.hasDriRenderNode) {
                        env.remove("LIBGL_ALWAYS_SOFTWARE")
                    }
                } else {
                    env["LIBGL_ALWAYS_SOFTWARE"] = "1"
                    env["GALLIUM_DRIVER"] = "virpipe"
                    env["MESA_GL_VERSION_OVERRIDE"] = "4.3COMPAT"
                    env["MESA_GLSL_VERSION_OVERRIDE"] = "430"
                }
                ResolvedGpuConfig(
                    requestedMode = requested,
                    activeBackend = "unified",
                    summary = summary,
                    requiresVirglServer = true,
                    enableVenus = enableVenus,
                    envVars = env,
                )
            }
            else -> {
                val summary = "Software Rendering (LLVMpipe + Lavapipe)"
                env["LINUXDROID_GPU_SUMMARY"] = summary
                env["LIBGL_ALWAYS_SOFTWARE"] = "1"
                env["GALLIUM_DRIVER"] = "llvmpipe"
                env["VK_DRIVER_FILES"] = LVP_ICD
                env["VK_ICD_FILENAMES"] = LVP_ICD
                ResolvedGpuConfig(
                    requestedMode = requested,
                    activeBackend = "software",
                    summary = summary,
                    requiresVirglServer = false,
                    enableVenus = false,
                    envVars = env,
                )
            }
        }
    }
}
